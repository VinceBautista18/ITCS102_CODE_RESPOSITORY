# + - addition
# - - subtraction
# * - multiplication
# / - division
# // - floor division (round down)
# ** - exponentation (exponents
# % - modulus 

a = 6
b = 5
sum = a + b
diff = a - b

print("The sum of ",a,"plus ",b, "is ",sum)
print("The sum of ",a,"minus ",b, "is ",diff)
print("The sum of ",a,"times ",b, "is ",a*b)
print("The sum of ",a,"divide ",b, "is ",a/b)
print("The sum of ",a,"divide ",b, "is ",a//b)
print("The sum of ",a,"exponentation ",b, "is ",a**b)
print("The sum of ",a,"modulus ",b, "is ",a%b)